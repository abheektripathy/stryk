#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
export LC_ALL=C

"${STRYK_QUASAR:-quasar}" idl programs/stryk
generated=target/client/rust/stryk-client/src
dest=crates/stryk-client/src/generated.rs
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
    echo '// Generated by scripts/generate-client.sh from the pinned Quasar Rust client.'
    printf '\nuse solana_address::Address;\nuse solana_instruction::{AccountMeta, Instruction};\n\n'
    sed -n '/^pub const ID:/p' "$generated/lib.rs"
    for source in "$generated"/instructions/*.rs; do
        [[ "$source" != */mod.rs ]] || continue
        printf '\n'
        sed -n '/^pub struct/,$p' "$source" | sed -E '
            s/Configure_laneInstruction/ConfigureLaneInstruction/g
            s/Fix_expiryInstruction/FixExpiryInstruction/g
            s/Initialize_capacityInstruction/InitializeCapacityInstruction/g
            s/Initialize_expiryInstruction/InitializeExpiryInstruction/g
            s/Initialize_marketInstruction/InitializeMarketInstruction/g
            s/Mark_no_fixInstruction/MarkNoFixInstruction/g
            s/Set_lane_enabledInstruction/SetLaneEnabledInstruction/g
            s/Set_market_pausedInstruction/SetMarketPausedInstruction/g
            s/Settle_positionInstruction/SettlePositionInstruction/g
        '
    done
} >"$tmp"

if [[ "${1:-}" == "--check" ]]; then
    diff -u "$dest" "$tmp"
else
    cp "$tmp" "$dest"
fi
